"""Shared helpers for Twin Turbo's asset generators: colour conversion, tile
slicing and de-duplication, Bayer dithering, and C array output."""
import numpy as np

BAYER4 = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]) / 16.0


def hexc(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rgb15(c):
    r, g, b = [max(0, min(31, int(round(v / 255 * 31)))) for v in c]
    return r | (g << 5) | (b << 10)


def pal15(cols):
    return [rgb15(hexc(c) if isinstance(c, str) else c) for c in cols]


def dither_ramp(v, ramp, x0=0, y0=0):
    """v: float array in [0,1]; ramp: list of palette indices dark->light.
    Ordered-dither between neighbouring ramp entries."""
    h, w = v.shape
    n = len(ramp)
    yy, xx = np.mgrid[0:h, 0:w]
    th = BAYER4[(yy + y0) % 4, (xx + x0) % 4]
    f = np.clip(v, 0, 1) * (n - 1)
    lo = np.floor(f).astype(int)
    frac = f - lo
    idx = np.where(frac > th, np.minimum(lo + 1, n - 1), lo)
    return np.array(ramp)[idx]


def tile4(a):
    """8x8 array of 4-bit indices -> 8 u32 words"""
    out = []
    for row in a:
        v = 0
        for k in range(8):
            v |= int(row[k] & 15) << (4 * k)
        out.append(v)
    return out


def tile8(a):
    """8x8 array of 8-bit indices -> 16 u32 words"""
    out = []
    flat = a.reshape(-1)
    for i in range(0, 64, 4):
        out.append(int(flat[i]) | int(flat[i + 1]) << 8 | int(flat[i + 2]) << 16 | int(flat[i + 3]) << 24)
    return out


def tiles_dedupe(img, bpp=4, flip=True, first_blank=True, start=None):
    """Slice img (h x w, multiples of 8) into tiles; returns (tiles words list,
    map entries list row-major, count). Map entries carry h/v flip bits when
    flip is allowed (regular BGs only)."""
    h, w = img.shape
    tiles = [] if start is None else list(start)
    lut = {}
    for i, t in enumerate(tiles):
        pass
    words_of = tile4 if bpp == 4 else tile8
    if first_blank and not tiles:
        z = np.zeros((8, 8), np.uint8)
        tiles.append(words_of(z))
        lut[z.tobytes()] = (0, 0)
    entries = []
    for ty in range(h // 8):
        for tx in range(w // 8):
            t = img[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8].astype(np.uint8)
            key = t.tobytes()
            if key in lut:
                idx, fl = lut[key]
                entries.append(idx | fl)
                continue
            found = None
            if flip:
                for fl, tt in ((0x400, t[:, ::-1]), (0x800, t[::-1, :]), (0xC00, t[::-1, ::-1])):
                    k2 = np.ascontiguousarray(tt).tobytes()
                    if k2 in lut and lut[k2][1] == 0:
                        found = (lut[k2][0], fl)
                        break
            if found:
                entries.append(found[0] | found[1])
                continue
            idx = len(tiles)
            tiles.append(words_of(t))
            lut[key] = (idx, 0)
            entries.append(idx)
    return tiles, entries


def obj_tiles(img, tw, th, bpp=4):
    """sprite of tw x th tiles -> words in 1D mapping order"""
    words = []
    fn = tile4 if bpp == 4 else tile8
    for ty in range(th):
        for tx in range(tw):
            words += fn(img[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8])
    return words


class CWriter:
    def __init__(self, path_c, path_h, header_comment):
        self.c = open(path_c, 'w')
        self.h = open(path_h, 'w')
        self.c.write('/* generated by %s */\n#include "%s"\n\n' % (header_comment, path_h.split('/')[-1]))
        self.h.write('/* generated by %s */\n#pragma once\n#include "../gba.h"\n\n' % header_comment)

    def arr(self, ctype, name, values, per_line=16, fmt='0x%08X' , align=4):
        values = list(values)
        self.h.write('extern const %s %s[%d];\n' % (ctype, name, len(values)))
        self.c.write('const %s %s[%d] __attribute__((aligned(%d))) = {\n' % (ctype, name, len(values), align))
        for i in range(0, len(values), per_line):
            self.c.write('  ' + ','.join(fmt % (v & (0xFFFFFFFF if '%08' in fmt else 0xFFFF if '%04' in fmt else 0xFF)) if fmt.startswith('0x') else fmt % v for v in values[i:i + per_line]) + ',\n')
        self.c.write('};\n')

    def u32(self, name, v):
        self.arr('u32', name, v, 8, '0x%08X')

    def u16(self, name, v):
        self.arr('u16', name, v, 16, '0x%04X')

    def s16(self, name, v):
        self.arr('s16', name, v, 16, '%d')

    def u8(self, name, v):
        self.arr('u8', name, v, 32, '%d')

    def s8(self, name, v):
        self.arr('s8', name, v, 32, '%d')

    def define(self, name, v):
        self.h.write('#define %s %s\n' % (name, v))

    def raw_h(self, s):
        self.h.write(s)

    def close(self):
        self.c.close()
        self.h.close()
