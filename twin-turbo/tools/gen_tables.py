#!/usr/bin/env python3
"""Lookup tables: sine (Q12, 256 steps per turn) and reciprocals for Mode 7."""
import os, math
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
with open(os.path.join(ROOT, 'src/gen/tables_gen.c'), 'w') as f:
    f.write('/* generated by tools/gen_tables.py */\n#include "../gba.h"\n')
    f.write('const s16 sin_lut[256] = {%s};\n' % ','.join(str(int(round(math.sin(i * 2 * math.pi / 256) * 4096))) for i in range(256)))
    f.write('const u16 recip_lut[256] = {%s};\n' % ','.join(str(min(65535, int(round(65536 / i)))) if i else '65535' for i in range(256)))
