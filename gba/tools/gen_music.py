#!/usr/bin/env python3
"""Convert the 4-track MIDI arrangements in music/*.mid (lead, harmony, bass,
drums; written by tools/compose.py) into PSG note data for the GBA
(src/gen/music_gen.c).

Each part becomes (note, frames) pairs, note 0 = rest; drums become
(1 kick | 2 snare | 3 hat | 4 open hat, frames). Timing runs on a 16th-note
grid with frame counts rounded cumulatively, so all four parts stay in step
for the whole loop. Needs pretty_midi.
"""
import os, sys
import pretty_midi

HERE = os.path.dirname(os.path.abspath(__file__))
MUSIC = os.path.join(HERE, '..', 'music')
OUT = os.path.join(HERE, '..', 'src', 'gen', 'music_gen.c')
FPS = 59.7275

SONGS = [
    # name, midi file, lead duty/envelope, harmony duty/envelope, bass volume/wave,
    # vibrato delay/depth. Duty 0-3 = 12.5/25/50/75%; envelope = volume << 4 | decay step.
    dict(name='song_menu', midi='menu.mid', lead=(2, 0xA5), harm=(1, 0x63), bass=(1, 0), vib=(14, 3)),
    dict(name='song_classic', midi='classic.mid', lead=(1, 0xB4), harm=(2, 0x52), bass=(1, 1), vib=(10, 4)),
    # relaxed: a round, plucked lead that rings out like a steel pan, soft stabs
    dict(name='song_relaxed', midi='relaxed.mid', lead=(2, 0xB3), harm=(2, 0x41), bass=(1, 0), vib=(20, 2)),
    # expert: a thin held lead with a wide, late vibrato over a punchy saw bass
    dict(name='song_expert', midi='expert.mid', lead=(1, 0xA0), harm=(2, 0x43), bass=(1, 1), vib=(16, 5)),
]
DRUMS = {35: 1, 36: 1, 38: 2, 40: 2, 39: 2, 42: 3, 44: 3, 46: 4}


def grid(pm):
    bpm = pm.get_tempo_changes()[1][0]
    return 60 / bpm / 4


def cells_of(inst, c, ncell):
    """Per-cell (pitch, onset) for a monophonic part."""
    line = [(0, False)] * ncell
    for n in sorted(inst.notes, key=lambda n: n.start):
        s, e = int(round(n.start / c)), int(round(n.end / c))
        for i in range(s, min(e, ncell)):
            line[i] = (n.pitch, i == s)
    return line


def to_events(line, frame_at):
    ev = []
    for i, (p, onset) in enumerate(line):
        dur = frame_at(i + 1) - frame_at(i)
        if ev and ev[-1][0] == p and not onset and ev[-1][1] + dur < 256:
            ev[-1][1] += dur
        else:
            ev.append([p, dur])
    return ev


def c_array(name, ev):
    flat = [v for e in ev for v in e]
    lines = ['  ' + ', '.join(str(v) for v in flat[i:i + 24]) + ',' for i in range(0, len(flat), 24)]
    return f'static const u8 {name}[] = {{\n' + '\n'.join(lines) + '\n};\n'


def main():
    out = ['/* generated by tools/gen_music.py from the MIDI files in music/ */', '#include "music_gen.h"', '']
    for sg in SONGS:
        name = sg['name']
        pm = pretty_midi.PrettyMIDI(os.path.join(MUSIC, sg['midi']))
        c = grid(pm)
        ncell = int(round(pm.get_end_time() / c)) // 16 * 16       # whole bars only
        frame_at = lambda i: int(round(i * c * FPS))
        parts = {i.name: i for i in pm.instruments}
        lead = to_events(cells_of(parts['lead'], c, ncell), frame_at)
        harm = to_events(cells_of(parts['harmony'], c, ncell), frame_at)
        bass = to_events(cells_of(parts['bass'], c, ncell), frame_at)
        hits = [0] * ncell
        for n in parts['drums'].notes:
            i = int(round(n.start / c))
            if i < ncell and n.pitch in DRUMS:
                hits[i] = DRUMS[n.pitch] if not hits[i] else min(hits[i], DRUMS[n.pitch])
        drums = to_events([(h, True) if h else (0, False) for h in hits], frame_at)
        p = name.replace('song_', '')
        for part, ev in (('lead', lead), ('harm', harm), ('bass', bass), ('drums', drums)):
            out.append(c_array(f'{p}_{part}', ev))
        out.append(f'const Song {name} = {{ {p}_lead, sizeof {p}_lead, {p}_harm, sizeof {p}_harm, {p}_bass, sizeof {p}_bass, '
                   f'{p}_drums, sizeof {p}_drums, 1, {sg["lead"][0]}, 0x{sg["lead"][1]:02X}, {sg["bass"][0]}, '
                   f'{sg["harm"][0]}, 0x{sg["harm"][1]:02X}, {sg["vib"][0]}, {sg["vib"][1]}, {sg["bass"][1]} }};\n')
        print(f'{name}: {ncell // 16} bars, {len(lead)} lead, {len(harm)} harmony, {len(bass)} bass, {len(drums)} drum events, '
              f'{frame_at(ncell) / FPS:.1f}s loop', file=sys.stderr)
    open(OUT, 'w').write('\n'.join(out))
    names = ', '.join(sg['name'] for sg in SONGS)
    open(OUT.replace('.c', '.h'), 'w').write(f'#pragma once\n#include "../sound.h"\nextern const Song {names};\n')


if __name__ == '__main__':
    main()
